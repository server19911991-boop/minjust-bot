#!/usr/bin/env python3
import json
import re

print("=" * 60)
print("🔧 ИСПРАВЛЕНИЕ И ДОБАВЛЕНИЕ ВСЕХ ВОПРОСОВ")
print("=" * 60)

# Читаем файл с вопросами
with open('Вопросы с экзамена с минюста.txt', 'r', encoding='utf-8') as f:
    content = f.read()

print("📂 Файл загружен, длина:", len(content))

# ============ ИСПРАВЛЕНИЕ ОШИБОК ============

# 1. Исправляем отсутствующие кавычки у id (вопросы 10, 14, 45, 46, 47, 61, 82)
content = re.sub(r'\{\s*\n\s*id":', r'{\n    "id":', content)

# 2. Исправляем вопрос 2 - отсутствует кавычка у question
content = re.sub(r'"question": "Заключение концессионных договоров без проведения конкурса \(аукциона\) ,', 
                 r'"question": "Заключение концессионных договоров без проведения конкурса (аукциона)",', content)

# 3. Вопрос 9 - убираем дублирование маркера
content = re.sub(r'\(Блок Вопросы с экзамена Минюста\) Статья 238 ТК \(Блок Вопросы с экзамена Минюста\)', 
                 r'(Блок Вопросы с экзамена Минюста) Статья 238 ТК', content)

# 4. Вопрос 13 - закрывающая кавычка у article
content = re.sub(r'"article": "\(Блок Вопросы с экзамена Минюста\) Статья 24\.59 КоАП \(в ответах верны 1-3\? Но в статье конкретно 1, 4 варианты правильные\) $',
                 r'"article": "(Блок Вопросы с экзамена Минюста) Статья 24.59 КоАП (в ответах верны 1-3? Но в статье конкретно 1, 4 варианты правильные)"', content)

# 5. Вопрос 16 - закрывающая кавычка у option
content = re.sub(r'"подлежат на официальных сайтах республиканского органа государственного управления\) $',
                 r'"подлежат на официальных сайтах республиканского органа государственного управления)"', content)

# 6. Вопрос 25 - закрывающая кавычка у option
content = re.sub(r'"Концессионый договор об оказании услуг \(выполнении работ\) ,',
                 r'"Концессионный договор об оказании услуг (выполнении работ)",', content)

# 7. Вопрос 28-38 - добавляем закрывающие кавычки к article
fixes = [
    (r'"article": "\(Блок Вопросы с экзамена Минюста\) Статья 71 Конституции$', 
     r'"article": "(Блок Вопросы с экзамена Минюста) Статья 71 Конституции"'),
    (r'"article": "\(Блок Вопросы с экзамена Минюста\) Статья 132 КГС$',
     r'"article": "(Блок Вопросы с экзамена Минюста) Статья 132 КГС"'),
    (r'"article": "\(Блок Вопросы с экзамена Минюста\) Пункт 92 Указа о проверках\.$',
     r'"article": "(Блок Вопросы с экзамена Минюста) Пункт 92 Указа о проверках"'),
    (r'"article": "\(Блок Вопросы с экзамена Минюста\) статья 4\.7 КоАП\.$',
     r'"article": "(Блок Вопросы с экзамена Минюста) статья 4.7 КоАП"'),
    (r'"article": "\(Блок Вопросы с экзамена Минюста\) Пункт 98 Указа о проверках\.$',
     r'"article": "(Блок Вопросы с экзамена Минюста) Пункт 98 Указа о проверках"'),
    (r'"article": "\(Блок Вопросы с экзамена Минюста\) Пункт 15 Закона об инвестициях\.$',
     r'"article": "(Блок Вопросы с экзамена Минюста) Пункт 15 Закона об инвестициях"'),
    (r'"article": "\(Блок Вопросы с экзамена Минюста\) статья 10 Закона о противодействии отмыванию$',
     r'"article": "(Блок Вопросы с экзамена Минюста) статья 10 Закона о противодействии отмыванию"'),
    (r'"article": "\(Блок Вопросы с экзамена Минюста\) статья 7 Закона об урегулировании неплатежеспособности$',
     r'"article": "(Блок Вопросы с экзамена Минюста) статья 7 Закона об урегулировании неплатежеспособности"'),
    (r'"article": "\(Блок Вопросы с экзамена Минюста\) статья 59 ГК$',
     r'"article": "(Блок Вопросы с экзамена Минюста) статья 59 ГК"'),
    (r'"article": "\(Блок Вопросы с экзамена Минюста\) статья 235 КТС$',
     r'"article": "(Блок Вопросы с экзамена Минюста) статья 235 КТС"'),
    (r'"article": "\(Блок Вопросы с экзамена Минюста\) пункт 14 статья 96 КГС$',
     r'"article": "(Блок Вопросы с экзамена Минюста) пункт 14 статья 96 КГС"'),
]

for pattern, replacement in fixes:
    content = re.sub(pattern, replacement, content)

# 8. Вопрос 44 - закрывающая кавычка у article
content = re.sub(r'"article": "\(Блок Вопросы с экзамена Минюста\) Часть 3 Статья 116 КГС \(в сроки, исчисляемые днями, не включаются нерабочие дни, если иное не предусмотрено настоящим Кодексом и иными законодательными актами\) $',
                 r'"article": "(Блок Вопросы с экзамена Минюста) Часть 3 Статья 116 КГС (в сроки, исчисляемые днями, не включаются нерабочие дни, если иное не предусмотрено настоящим Кодексом и иными законодательными актами)"', content)

# 9. Вопрос 60 - закрывающая кавычка у article
content = re.sub(r'"article": "\(Блок Вопросы с экзамена Минюста\) Пункт 1 статьи 276, 277 ГК \(помним, что кроме вышеизложенных еще оперативное управление может быть у казенных предприятий и религиозных организаций\) $',
                 r'"article": "(Блок Вопросы с экзамена Минюста) Пункт 1 статьи 276, 277 ГК (помним, что кроме вышеизложенных еще оперативное управление может быть у казенных предприятий и религиозных организаций)"', content)

# 10. Вопрос 66 - закрывающая кавычка у option
content = re.sub(r'приостановления\) ,', r'приостановления)",', content)

# 11. Вопрос 77 - закрывающие кавычки у options
content = re.sub(r'календарных дней до дня проведения конкурса \(аукциона\) ,', 
                 r'календарных дней до дня проведения конкурса (аукциона)",', content)

# 12. Вопрос 81 - закрывающая кавычка у article
content = re.sub(r'депозитов\) $', r'депозитов))"', content)

# 13. Вопрос 89 - закрывающие кавычки у options
content = re.sub(r'решением\) ,', r'решением)",', content)

# 14. Вопрос 90 - закрывающая кавычка у option
content = re.sub(r'наблюдательный совет\) ,', r'наблюдательный совет)",', content)

# 15. Вопрос 117 - закрывающие кавычки у options
content = re.sub(r'другие\) ,', r'другие)",', content)
content = re.sub(r'другие\) $', r'другие)"', content)

# 16. Убираем лишние запятые
content = re.sub(r',\s*}', '}', content)
content = re.sub(r',\s*]', ']', content)

# 17. Добавляем недостающие запятые между объектами
content = re.sub(r'}\s*{', '},\n{', content)

# Сохраняем исправленный файл
with open('Вопросы с экзамена с минюста_fixed.json', 'w', encoding='utf-8') as f:
    f.write(content)

print("💾 Сохранено в: Вопросы с экзамена с минюста_fixed.json")

# ============ ПРОВЕРКА И ДОБАВЛЕНИЕ ============

try:
    with open('Вопросы с экзамена с минюста_fixed.json', 'r', encoding='utf-8') as f:
        exam_questions = json.load(f)
    
    print(f"✅ Загружено {len(exam_questions)} вопросов из файла")
    
    # Загружаем основной файл
    with open('questions.json', 'r', encoding='utf-8') as f:
        main_questions = json.load(f)
    
    print(f"📚 В основном файле: {len(main_questions)} вопросов")
    
    # Находим максимальный ID
    max_id = max([q.get('id', 0) for q in main_questions]) if main_questions else 0
    
    # Добавляем вопросы, которых ещё нет
    added = 0
    existing_questions = set()
    for q in main_questions:
        existing_questions.add(q.get('question', ''))
    
    for q in exam_questions:
        question_text = q.get('question', '')
        if question_text not in existing_questions:
            max_id += 1
            q['id'] = max_id
            # Добавляем маркер, если его нет
            if '(Блок Вопросы с экзамена Минюста)' not in q.get('article', ''):
                q['article'] = f"{q.get('article', '')} (Блок Вопросы с экзамена Минюста)"
            if 'category' in q:
                del q['category']
            main_questions.append(q)
            added += 1
            existing_questions.add(question_text)
    
    print(f"✅ Добавлено {added} новых вопросов")
    
    # Сохраняем
    with open('questions.json', 'w', encoding='utf-8') as f:
        json.dump(main_questions, f, ensure_ascii=False, indent=4)
    
    print(f"📚 Всего вопросов: {len(main_questions)}")
    
    # Считаем вопросы с маркером
    exam_count = sum(1 for q in main_questions if '(Блок Вопросы с экзамена Минюста)' in q.get('article', ''))
    print(f"📝 Вопросов с маркером '(Блок Вопросы с экзамена Минюста)': {exam_count}")
    
    print("\n" + "=" * 60)
    print("✅ ГОТОВО! Все вопросы добавлены.")
    print("🔄 Перезапустите бота: python3 bot.py")
    
except json.JSONDecodeError as e:
    print(f"\n❌ Ошибка в JSON: {e}")
    print("\n📝 Некоторые вопросы не удалось исправить автоматически.")
    print("   Проверьте файл вручную: nano Вопросы с экзамена с минюста_fixed.json")
